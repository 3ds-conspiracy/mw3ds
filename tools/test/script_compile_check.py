"""Checks the 3DS script compiler (source/components/compiler/compiler.cpp) against the PC one (tools/convert/mwscript.py).

The engine compiles console lines itself; the converter compiles the game's scripts. Both must build the same
tree, so this compiles every script and dialogue result of the load order with both and compares them. The C++
side's function tables (source/components/compiler/extensions0.hpp) are generated from mwscript.py's, so they cannot drift.

Usage:
    python tools/test/script_compile_check.py --tables   # rewrite source/components/compiler/extensions0.hpp from mwscript.py
    python tools/test/script_compile_check.py            # tables current? then compile everything both ways
    python tools/test/script_compile_check.py --show 5   # print the first 5 differences in full
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "tools" / "convert"))

import mwscript  # noqa: E402

TABLES = ROOT / "source" / "components" / "compiler" / "extensions0.hpp"
OUT = ROOT / "build" / "scriptc-check"
EXE = OUT / "scriptc-check.exe"
SOURCES = [ROOT / "tools/test/native/scriptc_check.cpp", ROOT / "source/components/compiler/compiler.cpp", ROOT / "source/extern/cjson/cJSON.c"]


def tables_text():
    def q(s):
        return '"' + s + '"'
    lines = ["// Generated by tools/test/script_compile_check.py --tables from tools/convert/mwscript.py's tables:",
             "// OpenMW's script functions (result type, arguments) and instructions (arguments). Do not edit.",
             "#pragma once", "",
             "struct ScFunc { const char* name; char type; const char* sig; };",
             "struct ScInstr { const char* name; const char* sig; };",
             "struct ScArity { const char* name; int count; };", "",
             "static const ScFunc kScFuncs[] = {"]
    lines += [f"\t{{ {q(n)}, '{t}', {q(s)} }}," for n, (t, s) in sorted(mwscript.FUNCS.items())]
    lines += ["};", "", "static const ScInstr kScInstrs[] = {"]
    lines += [f"\t{{ {q(n)}, {q(s)} }}," for n, s in sorted(mwscript.INSTRS.items())]
    lines += ["};", "", "// Functions in expressions the signature tables do not cover: how many arguments they take",
              "static const ScArity kScExprArity[] = {"]
    lines += [f"\t{{ {q(n)}, {c} }}," for n, c in sorted(mwscript.EXPR_ARITY.items())]
    lines += ["};", "", "// Called without a reference, these need none (OpenMW): any other needs an object in context",
              "static const char* kScNoRefNeeded[] = {"]
    lines += [f"\t{q(n)}," for n in sorted(mwscript.NO_REF_NEEDED)]
    lines += ["};", ""]
    for name, seq in (("kScAttrs", mwscript._ATTRS), ("kScDynamics", mwscript._DYN), ("kScSkills", mwscript._SKILLS),
                      ("kScEffects", mwscript._EFFECTS)):
        lines.append(f"static const char* {name}[] = {{ " + ", ".join(q(s) for s in seq) + " };")
    return "\n".join(lines) + "\n"


def build_exe():
    OUT.mkdir(parents=True, exist_ok=True)
    newest = max(p.stat().st_mtime for p in SOURCES + [TABLES, ROOT / "source/components/compiler/compiler.hpp"])
    if EXE.exists() and EXE.stat().st_mtime > newest:
        return
    zig = [sys.executable, "-m", "ziglang"]
    cjson = OUT / "cJSON.o"
    steps = [zig + ["cc", "-c", "-O1", "-w", "-I", str(ROOT / "source"), str(ROOT / "source/extern/cjson/cJSON.c"), "-o", str(cjson)],
             zig + ["c++", "-O1", "-std=c++17", "-w", "-I", str(ROOT / "source"),
                    *[str(p) for p in SOURCES if p.suffix == ".cpp"], str(cjson), "-o", str(EXE)]]
    for cmd in steps:
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit("build failed:\n" + r.stderr[:4000])


def cases():
    """Every script, and every dialogue result (with and without speaker locals), with mwscript.py's result"""
    import mwfiles
    db = mwfiles.load_db()
    glob = {k: v[0] for k, v in db["GLOB"].items()}
    out = []

    def add(kind, ident, text, local_names=()):
        try:
            tree = (mwscript.compile_script(text, glob) if kind == "script"
                    else mwscript.compile_snippet(text, glob, local_names))
            want = {"ok": tree}
        except (mwscript.ScriptError, IndexError):
            want = {"error": True}
        out.append({"kind": kind, "id": ident, "text": text, "locals": list(local_names), "want": want})

    for name, text in db["SCPT"].items():
        add("script", name, text)
    some_locals = ("nolore", "companion", "state", "done", "count")
    for dial in db["dialogue"]:
        for info in dial["infos"]:
            src = info.zstr("BNAM") or ""
            if src.strip():
                ident = f"{dial['name']}/{info.zstr('INAM')}"
                add("snippet", ident, src)
                add("snippet", ident + " (locals)", src, some_locals)
    return glob, out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tables", action="store_true", help="rewrite source/components/compiler/extensions0.hpp")
    ap.add_argument("--show", type=int, default=3, help="differences to print in full")
    args = ap.parse_args()
    text = tables_text()
    if args.tables:
        TABLES.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {TABLES.relative_to(ROOT)}")
        return
    if not TABLES.exists() or TABLES.read_text(encoding="utf-8") != text:
        sys.exit("source/components/compiler/extensions0.hpp is out of date: run with --tables")
    build_exe()
    glob, items = cases()
    OUT.mkdir(parents=True, exist_ok=True)
    src = OUT / "cases.json"
    src.write_text(json.dumps({"globals": glob, "cases": [{k: c[k] for k in ("kind", "text", "locals")} for c in items]}),
                   encoding="utf-8")
    res = subprocess.run([str(EXE), str(src)], capture_output=True, text=True, encoding="utf-8")
    if res.returncode:
        sys.exit("checker failed:\n" + res.stderr[:4000])
    got = json.loads(res.stdout)
    bad = [(c, g) for c, g in zip(items, got) if ("error" in c["want"]) != ("error" in g)
           or ("ok" in g and g["ok"] != c["want"].get("ok"))]
    scripts = sum(c["kind"] == "script" for c in items)
    print(f"{len(items)} compiled ({scripts} scripts, {len(items) - scripts} dialogue results): {len(bad)} differ")
    for c, g in bad[:args.show]:
        print(f"\n--- {c['kind']} {c['id']}\n{c['text'][:600]}\nmwscript.py: {json.dumps(c['want'])[:1500]}"
              f"\nscriptc.cpp: {json.dumps(g)[:1500]}")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
