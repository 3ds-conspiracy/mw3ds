"""Rule x source x effect matrix: every rule an effect is held to, on every way an effect can reach the player, for each
kind of effect.

  python tools/test/specgen_matrix.py              writes tools/test/cases/spec-matrix-<rule>-<effect>-<source>.txt
  python tools/test/run_native_all.py --ignore-warnings --filter 'spec-matrix-*'

The bugs that slip past formula tests are paths: the rule is right and a source never runs it (the Boots of Blinding
Speed ignored Resist Magicka because a worn item's effects were applied with no resistance at all; constant effects took
their maximum while spells rolled between min and max). OpenMW applies one pipeline to every source (activespells.cpp
adds the effect, spelleffects.cpp resists, rolls and expires it), so each rule below is stated once, from that pipeline,
and run through each source that reaches it. A new source, rule or effect is one entry here and adds cases.

Sources (how the effect arrives):
  spell      a made spell, cast on the player (range self)
  use        an enchantment cast when used, on a ring
  once       an enchantment cast once (a scroll's way)
  constant   an enchantment worn: applied once as it is put on, no duration, never dispelled
  potion     a brewed potion drunk (its effects are the alchemy's: only Drain Fatigue, and only the rules that need no
             set magnitude)

Effects (what each is read back as: a change from a snapshot taken before):
  Drain Fatigue, Blind                       the effect's own total (harmful, Resist Magicka applies)
  Drain Attribute (Strength), Drain Skill    the attribute / skill itself falls (harmful)
  Fortify Attribute, Fortify Skill,          the attribute / skill / maximum rises (beneficial: Resist Magicka leaves it)
  Fortify Health
  Resist Fire                                the effect's own total (beneficial)
Willpower and Luck are 5 so the resistance roll's own share (x / roll) stays under a point; Strength and the skill start
at 50 so a rise or fall is never cut by 0 or 100.

Rules (what each is: the OpenMW rule it pins):
  applies      with no resistance the effect is there, by its magnitude
  resist       with 100% Resist Magicka a harmful effect is resisted (spelleffects.cpp: Fully resisted removes it); a
               beneficial one is not touched
  range        a magnitude range rolls between min and max, and two rolls on one seed differ (once the worn item's own
               die took the top every time)
  duration     a timed effect ends when its duration does; lasts: a worn constant one does not end by time
  dispel       Dispel removes a spell's effects, and only those: an item's (cast when used, once, worn) and a potion's
               stay (spelleffects.cpp: the purge takes Flag_Temporary active spells whose record is a Spell)
"""
from pathlib import Path

CASES = Path(__file__).resolve().parent / "cases"
NOTE = "# Generated by tools/test/specgen_matrix.py: edit the generator, not this file"
BASE_ITEM = "expensive_ring_01"
SCHOOLS = ["destruction", "alteration", "illusion", "conjuration", "mysticism", "restoration"]
MAG = 20                                   # the magnitude a fixed case gives

# name: (effect id, attribute/skill arg, what is read, the argument of that read, sign of the change, harmful)
PROBES = {
    "drain-fatigue": (20, "-", "effect", "20", +1, True),
    "blind": (47, "-", "effect", "47", +1, True),
    "drain-strength": (17, "strength", "attr", "strength", -1, True),
    "drain-axe": (21, "axe", "skill", "axe", -1, True),
    "fortify-strength": (79, "strength", "attr", "strength", +1, False),
    "fortify-axe": (83, "axe", "skill", "axe", +1, False),
    "fortify-health": (80, "-", "healthmax", "", +1, False),
    "resist-fire": (90, "-", "effect", "90", +1, False),
}
# what each source can be checked with
SOURCES = {
    "spell": {"timed": True, "ranged": True},
    "use": {"timed": True, "ranged": True},
    "once": {"timed": True, "ranged": True},
    "constant": {"timed": False, "ranged": True},
    "potion": {"timed": False, "ranged": False},          # (a potion's magnitude and duration are the alchemy's)
}


class Case:
    def __init__(self, rule, probe, source, why):
        self.name = f"spec-matrix-{rule}-{probe}-{source}"
        self.probe, self.source = probe, source
        self.effect, self.arg, self.kind, self.karg, self.sign, self.harmful = PROBES[probe]
        self.key = f"{self.kind}:{self.karg}" if self.karg else self.kind
        self.lines = [NOTE, f"# {why}", "3 0 0 0 0 MSG", "0.3 0 0 0 0 SEED:1"]
        self.n = 0
        self.item = ""                       # the made item the last deliver used (use, once, constant)

    def step(self, tok, secs=0.3):
        self.lines.append(f"{secs} 0 0 0 0 {tok}")

    def wait(self, secs):
        self.lines.append(f"{secs} 0 0 0")

    def stats(self):
        """Low Willpower and Luck, middling Strength and Axe, skill for the casts, and then the snapshot the checks read
        their change against."""
        self.step("SETATTR:willpower:5+SETATTR:luck:5+SETATTR:strength:50")
        self.step("SETATTR:intelligence:100")
        for s in SCHOOLS + ["alchemy"]:
            self.step(f"SETSKILL:{s}:100", 0.1)
        self.step("SETSKILL:axe:50", 0.1)
        self.refill()
        self.snap()

    def refill(self):
        self.step("FILL", 0.1)
        self.step("SETMAGICKA:9999", 0.1)

    def snap(self):
        self.step(f"SNAP:{self.key}", 0.1)

    def deliver(self, lo=MAG, hi=MAG, dur=20, wait=2.0):
        """Put the effect on the player by this case's source."""
        self.n += 1
        src = self.source
        if src == "potion":
            for item in ("apparatus_a_mortar_01", "ingred_marshmerrow_01", "ingred_coprinus_01"):
                self.step(f"GIVE:{item}", 0.1)
            self.step("BREW:ingred_marshmerrow_01:ingred_coprinus_01")
            self.wait(0.5)
            self.step("DRINKBREWED")
        else:
            self.step(f"ADDEFFECT:{self.effect}:{lo}:{hi}:{dur}:0:{self.arg}:0", 0.1)
            if src == "spell":
                self.step(f"MAKESPELL:m{self.n}", 0.1)
                self.step(f"CAST:mw3ds_test_m{self.n}")
            else:
                self.item = f"matrix_{self.n}"
                self.step(f"MAKEITEM:{BASE_ITEM}:{self.item}:{'once' if src == 'once' else 'constant' if src == 'constant' else 'use'}")
                self.step("EQUIPMADE" if src == "constant" else "USEMADE")
        self.wait(wait)

    def resist(self, pct=100, seconds=600):
        self.step(f"ACTIVE:93:{pct}:{seconds}", 0.1)       # Resist Magicka
        self.wait(0.3)

    def change(self, lo, hi):
        """The read-back is the snapshot plus a change between lo and hi (in the effect's own direction)."""
        a, b = sorted((self.sign * lo, self.sign * hi))
        self.step(f"EXPECT:{self.key}:ge:@{a - 0.5:g}+EXPECT:{self.key}:le:@{b + 0.5:g}", 0.1)

    def present(self):
        """There, by whatever magnitude (a potion's is the alchemy's)."""
        self.step(f"EXPECT:{self.key}:ge:@{0.5 if self.sign > 0 else -1000:g}+EXPECT:{self.key}:le:@{1000 if self.sign > 0 else -0.5:g}", 0.1)

    def unchanged(self):
        self.step(f"EXPECT:{self.key}:ge:@-0.01+EXPECT:{self.key}:le:@0.01", 0.1)

    def there(self):
        if self.source == "potion":
            self.present()
        else:
            self.change(MAG, MAG)

    def write(self):
        (CASES / f"{self.name}.txt").write_text("\n".join(self.lines) + "\n", newline="\n")


def applies(probe, source):
    c = Case("applies", probe, source, f"With no resistance a {source} {probe} effect is on the player, by its magnitude.")
    c.stats()
    c.deliver()
    c.there()
    return c


def resist(probe, source):
    harmful = PROBES[probe][5]
    c = Case("resist", probe, source,
             f"With 100% Resist Magicka a {source} {probe} effect is " + ("resisted: it never takes hold." if harmful
                                                                          else "not touched: it is a beneficial one."))
    c.stats()
    c.resist()
    c.deliver()
    if harmful:
        c.unchanged()
    else:
        c.there()
    return c


def range_(probe, source):
    c = Case("range", probe, source, f"A {source} {probe} effect with magnitudes 1 to 40 is rolled between them" +
             (", and two rolls on one seed are not the same number (the worn item's own die took the top every time "
              "once)." if PROBES[probe][2] == "effect" else "."))
    c.stats()
    absolute = PROBES[probe][2] == "effect"           # (an effect's own total starts at 0: the snapshot can be spent on a roll)
    for k in range(4):
        c.refill()
        c.deliver(1, 40, 2, wait=1.0)
        if absolute:
            c.step(f"EXPECT:{c.key}:ge:1+EXPECT:{c.key}:le:40", 0.1)
            if k == 0:
                c.step(f"SNAP:{c.key}", 0.1)
            elif k == 1:
                c.step(f"EXPECT:{c.key}:ne:@", 0.1)
        else:
            c.change(1, 40)
        if source == "constant":
            c.step(f"UNEQUIP:{c.item}", 0.1)
        c.wait(3)                                            # (a timed effect ends before the next roll)
    return c


def duration(probe, source):
    c = Case("duration", probe, source, f"A timed {source} {probe} effect (3 seconds) is on while it lasts and gone after.")
    c.stats()
    c.deliver(MAG, MAG, 3, wait=1.0)
    c.change(MAG, MAG)
    c.wait(6)
    c.unchanged()
    return c


def lasts(probe):
    c = Case("lasts", probe, "constant", f"A worn constant {probe} effect has no duration: still there long after any "
                                         "timed effect would have ended.")
    c.stats()
    c.deliver(MAG, MAG, 1, wait=1.0)
    c.change(MAG, MAG)
    c.wait(10)
    c.change(MAG, MAG)
    return c


def dispel(probe, source):
    stays = source != "spell"
    c = Case("dispel", probe, source, f"Dispel on the player {'leaves' if stays else 'removes'} a {source} {probe} effect.")
    c.stats()
    c.deliver(MAG, MAG, 30, wait=1.0)
    c.there()
    c.refill()
    c.step("ADDEFFECT:57:100:100:1:0:-:0", 0.1)               # Dispel
    c.step("MAKESPELL:dispel", 0.1)
    c.step("CAST:mw3ds_test_dispel")
    c.wait(2)
    if stays:
        c.there()
    else:
        c.unchanged()
    return c


def main():
    for old in CASES.glob("spec-matrix-*.txt"):
        old.unlink()
    n = 0
    for probe in PROBES:
        for source, caps in SOURCES.items():
            if source == "potion" and probe != "drain-fatigue":
                continue
            made = [applies(probe, source), resist(probe, source), dispel(probe, source)]
            if caps["ranged"]:
                made.append(range_(probe, source))
            if caps["timed"]:
                made.append(duration(probe, source))
            for c in made:
                c.write()
                n += 1
        lasts(probe).write()
        n += 1
    print(f"wrote {n} cases")


if __name__ == "__main__":
    main()
