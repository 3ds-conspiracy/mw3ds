"""Runs every case in tools/test/cases on the native (PC) build, several at a time, and saves the results:
    python tools/test/run_native_all.py [--filter 'mq-*' 'bug-*'] [--jobs 8] [--data out/world] [--start 'Seyda Neen']
                                        [--wait 600] [--build] [--ignore-warnings]
  --ignore-warnings   monitor warnings (floors, textures, memory ...) do not fail a case; failed expectations, driver
                      failures and runs that die still do
-> build/native-results/<stamp>/{summary.txt, results.csv, logs/<case>.log, out/<case>.txt}; the newest run is also
   copied to build/native-results/latest/.  chain-* cases (generated by run_suite.py --chained, each needs the one
   before it) are left out unless named in --filter.
Each case gets its own SD folder (build/native/sd-<slot>), so they do not touch each other's logs or saves.
--exe / --sd-root / --no-latest: another native build (build.py with MW3DS_NATIVE_BUILD), its own SD folders, and no copy
to build/native-results/latest (a second session's run that leaves the first one's alone)
--old3ds: every case with the Old 3DS profile (slow CPU, small heap: include/console.h), as run_test.py --old3ds
"""
import argparse
import csv
import fnmatch
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import mwtools

ROOT = mwtools.ROOT
SWEEP_CASE = re.compile(r"^(qrun|srun|xrun)-\d+$")


def select_cases(filters, old3ds):
    cases = sorted(p.stem for p in mwtools.CASES.glob("*.txt"))
    if filters:
        cases = [c for c in cases if any(fnmatch.fnmatchcase(c.lower(), f.lower()) for f in filters)]
    else:
        # (chain-*: made by run_suite --chained; zz-open-*: known open bugs, run by name)
        cases = [c for c in cases if not c.startswith(("chain-", "zz-open-"))]
    # A case for one console says so in its first lines, "# console: new" or "# console: old" (issue-32 pins the New 3DS's
    # animation rates, issue-32-old3ds the Old 3DS profile's): left out of a run with the other profile
    # A case only the emulator can judge says "# run: emulator" (bug-quit-black-screen: the exit with the data as romfs;
    # the native build ends its run straight after the save): left out of native runs the same way
    console = "old" if old3ds else "new"
    other = []
    for c in cases:
        for ln in mwtools.read_lines(mwtools.CASES / f"{c}.txt")[:5]:
            m = re.match(r"^#\s*console:\s*(new|old)\s*$", ln)
            if (m and m.group(1) != console) or re.match(r"^#\s*run:\s*emulator\s*$", ln):
                other.append(c)
                break
    return [c for c in cases if c not in other], other


def past_timings():
    """Seconds each case took in earlier runs (the newest wins)."""
    took = {}
    results = ROOT / "build" / "native-results"
    for d in sorted(p for p in results.glob("*") if p.is_dir() and p.name != "latest"):
        csv_file = d / "results.csv"
        if csv_file.exists():
            with open(csv_file, newline="", encoding="utf-8-sig") as f:
                for row in csv.DictReader(f):
                    took[row["case"]] = int(row["seconds"])
    return took


def judge(case, slot_id, started, a, log_dir, out_dir, total, done_count):
    """The row for a finished case."""
    out_file = out_dir / f"{case}.txt"
    out = mwtools.read_lines(out_file) if out_file.exists() else []
    verdict = next((ln for ln in out if ln.startswith("RESULT:")), "RESULT: FAIL (no result: the run died or timed out)")
    sd_log = ROOT / a.sd_root / f"sd-{slot_id}" / "3ds" / "mw3ds" / "log.txt"
    if sd_log.exists():
        shutil.copy2(sd_log, log_dir / f"{case}.log")
    passed = verdict.startswith("RESULT: PASS")
    m = re.search(r"(\d+) monitor warnings", verdict)
    warn = int(m.group(1)) if m else 0
    if not passed and a.ignore_warnings and re.match(
            r"^RESULT: FAIL \(\d+ expectations met, 0 failed, 0 driver failures, \d+ monitor warnings(\)|;)", verdict):
        passed = True
    detail = re.sub(r"^RESULT: (PASS|FAIL) ?", "", verdict)
    # Sweep batches (qrun / srun / xrun) try each quest's opener and are judged by how many quests started
    # (questrun.py --check), not by RESULT: a "topic not offered" there is a finding about that quest. A batch passes
    # when it starts at least as many quests as the emulator sweep did (build/<prefix>-results.txt), else when none fail.
    if SWEEP_CASE.match(case):
        warn = 0
        r = subprocess.run([sys.executable, str(mwtools.TEST_DIR / "questrun.py"), "--check", case,
                            "--log", str(log_dir / f"{case}.log")], capture_output=True, text=True, errors="replace")
        check = (r.stdout + r.stderr).splitlines()
        (log_dir / f"{case}.check.txt").write_text("\n".join(check) + "\n", encoding="utf-8")
        mine = [ln for ln in check if re.match(rf"^{re.escape(case)}: (\d+) started, (\d+) not", ln)]
        m = re.search(r": (\d+) started, (\d+) not", mine[-1]) if mine else None
        if m:
            n_started, not_started = int(m.group(1)), int(m.group(2))
            base = None
            base_file = ROOT / "build" / f"{re.sub(r'-\d+$', '', case)}-results.txt"
            if base_file.exists():
                hits = [ln for ln in mwtools.read_lines(base_file) if re.match(rf"^{re.escape(case)}: (\d+) started, (\d+) not", ln)]
                if hits:
                    base = int(re.search(r": (\d+) started", hits[-1]).group(1))
            passed = n_started >= base if base is not None else not_started == 0
            detail = f"sweep: {n_started} started, {not_started} not" + (
                f" (emulator sweep: {base} started)" if base is not None else " (no emulator baseline)")
        else:
            passed = False
            detail = "sweep: no check result (" + (check[-1] if check else "") + ")"
    print(f"{done_count:4}/{total}  {'PASS' if passed else 'FAIL':<4}  {case}", flush=True)
    return {"case": case, "result": "PASS" if passed else "FAIL", "warnings": warn,
            "seconds": int(time.time() - started), "detail": detail}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--filter", nargs="*", default=[])
    ap.add_argument("--jobs", type=int, default=0)
    ap.add_argument("--data", default="out/world")
    ap.add_argument("--start", default="Seyda Neen")
    ap.add_argument("--wait", type=int, default=600)
    ap.add_argument("--build", action="store_true")
    ap.add_argument("--ignore-warnings", action="store_true")
    ap.add_argument("--exe", default="")
    ap.add_argument("--sd-root", default="build/native")
    ap.add_argument("--no-latest", action="store_true")
    ap.add_argument("--old3ds", action="store_true")
    a = ap.parse_args()

    jobs = a.jobs if a.jobs > 0 else max(1, (os.cpu_count() or 2) - 2)
    default_exe = ROOT / mwtools.NATIVE_EXE
    if not a.exe and (a.build or not default_exe.exists()):
        if subprocess.run([sys.executable, str(mwtools.TEST_DIR / "native" / "build.py")]).returncode != 0:
            print("native build failed")
            return 1
    # The binary as it is now: a rebuild during the run must not change what the cases run
    exe = str(Path(a.exe).resolve()) if a.exe else str(default_exe)

    filters = [f for part in a.filter for f in part.split(",") if f]
    cases, other_console = select_cases(filters, a.old3ds)
    if not cases:
        print("no cases match")
        return 1
    # The longest first (as the last runs timed them; uber-* first when they haven't been timed): a five-minute uber case
    # started last kept the run going long after the others were done
    took = past_timings()
    cases.sort(key=lambda c: (-(took[c] if c in took else 100000 if c.startswith("uber-") else 5), c))

    stamp = time.strftime("%Y%m%d-%H%M%S")
    res_dir = ROOT / "build" / "native-results" / stamp
    log_dir, out_dir = res_dir / "logs", res_dir / "out"
    log_dir.mkdir(parents=True, exist_ok=True)
    out_dir.mkdir(parents=True, exist_ok=True)

    slots = [{"id": i, "proc": None, "case": None, "started": 0.0, "files": []} for i in range(jobs)]
    queue = list(cases)
    rows = []
    total = len(cases)
    clock = time.time()

    def finish(slot):
        for f in slot["files"]:
            f.close()
        rows.append(judge(slot["case"], slot["id"], slot["started"], a, log_dir, out_dir, total, len(rows) + 1))
        slot["proc"] = None

    while queue or any(s["proc"] for s in slots):
        for slot in slots:
            if slot["proc"] and slot["proc"].poll() is not None:
                finish(slot)
            if not slot["proc"] and queue:
                case = queue.pop(0)
                slot["case"], slot["started"] = case, time.time()
                sd = ROOT / a.sd_root / f"sd-{slot['id']}"
                cmd = [sys.executable, str(mwtools.TEST_DIR / "run_test.py"), case, "--native", "--sd", str(sd),
                       "--data", a.data, "--start", a.start, "--wait", str(a.wait), "--exe", exe]
                if a.old3ds:
                    cmd.append("--old3ds")
                out_f = open(out_dir / f"{case}.txt", "w", encoding="utf-8")
                err_f = open(out_dir / f"{case}.err", "w", encoding="utf-8")
                slot["files"] = [out_f, err_f]
                slot["proc"] = subprocess.Popen(cmd, stdout=out_f, stderr=err_f, creationflags=mwtools.hidden_flags())
            if slot["proc"] and time.time() - slot["started"] > a.wait + 60:
                mwtools.kill_tree(slot["proc"])
        time.sleep(0.3)

    rows.sort(key=lambda r: r["case"])
    with open(res_dir / "results.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["case", "result", "warnings", "seconds", "detail"], quoting=csv.QUOTE_ALL)
        w.writeheader()
        w.writerows(rows)
    passed = [r for r in rows if r["result"] == "PASS"]
    failed = [r for r in rows if r["result"] == "FAIL"]
    mode = ", monitor warnings ignored" if a.ignore_warnings else ""
    lines = [f"native run {stamp}: {len(passed)} of {total} passed in {int(time.time() - clock)} s ({jobs} at a time, data {a.data}{mode})"]
    if other_console:
        lines.append(f"left out, for the other console or the emulator only: {', '.join(other_console)}")
    lines += ["", f"SUCCEEDED ({len(passed)}):"]
    for r in passed:
        extra = f"  {r['detail']}" if r["detail"].startswith("sweep:") else (f"  ({r['warnings']} warnings ignored)" if r["warnings"] else "")
        lines.append(f"  {r['case']}{extra}")
    if failed:
        lines += ["", f"FAILED ({len(failed)}):"]
        lines += [f"  {r['case']}  {r['detail']}" for r in failed]
    (res_dir / "summary.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    if not a.no_latest:
        latest = ROOT / "build" / "native-results" / "latest"
        shutil.rmtree(latest, ignore_errors=True)
        shutil.copytree(res_dir, latest)
    print()
    print("\n".join(lines))
    print(f"saved: {res_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
